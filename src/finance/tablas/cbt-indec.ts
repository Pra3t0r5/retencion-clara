export function getCBT(yearMonth: string): number {
  return CBT_ARS[yearMonth] ?? Object.values(CBT_ARS).at(-1) ?? 3_350_000;
}

// How many CBT does netUSD cover, given MEP rate
export function getCanastas(netUSD: number, tcMEP: number, yearMonth: string): number {
  const cbt = getCBT(yearMonth);
  if (cbt === 0 || tcMEP === 0) return 0;
  return (netUSD * tcMEP) / cbt;
}
